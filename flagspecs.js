// 렌더러 — bbox(x,y,w,h) 안에 spec을 그린다. 호출측에서 나라 폴리곤으로 클리핑한 상태.
export function drawFlag(ctx, spec, x, y, w, h) {
  if (!spec) { ctx.fillStyle = '#8a9aa8'; ctx.fillRect(x, y, w, h); return; }
  const c = spec.c || ['#8a9aa8'];

  if (spec.t === 's') {
    ctx.fillStyle = c[0];
    ctx.fillRect(x, y, w, h);
  } else if (spec.t === 'h') {
    const ratios = spec.r || c.map(() => 1 / c.length);
    let yy = y;
    for (let i = 0; i < c.length; i++) {
      const hh = h * ratios[i];
      ctx.fillStyle = c[i];
      ctx.fillRect(x, yy, w, hh + 0.6);
      yy += hh;
    }
  } else if (spec.t === 'v') {
    const ratios = spec.r || c.map(() => 1 / c.length);
    let xx = x;
    for (let i = 0; i < c.length; i++) {
      const ww = w * ratios[i];
      ctx.fillStyle = c[i];
      ctx.fillRect(xx, y, ww + 0.6, h);
      xx += ww;
    }
  } else if (spec.t === 'nordic') {
    ctx.fillStyle = c[0];
    ctx.fillRect(x, y, w, h);
    const vx = x + w * 0.38, hy = y + h * 0.5;
    ctx.fillStyle = c[1];
    ctx.fillRect(vx - w * 0.09, y, w * 0.18, h);
    ctx.fillRect(x, hy - h * 0.11, w, h * 0.22);
    if (c[2]) {
      ctx.fillStyle = c[2];
      ctx.fillRect(vx - w * 0.045, y, w * 0.09, h);
      ctx.fillRect(x, hy - h * 0.055, w, h * 0.11);
    }
  } else if (spec.t === 'diag') {
    ctx.fillStyle = c[0];
    ctx.fillRect(x, y, w, h);
    ctx.fillStyle = c[1];
    ctx.beginPath();
    ctx.moveTo(x, y + h); ctx.lineTo(x + w, y); ctx.lineTo(x + w, y + h);
    ctx.closePath(); ctx.fill();
    if (c[2]) { // 대각 띠
      ctx.strokeStyle = c[2];
      ctx.lineWidth = Math.max(1.5, h * 0.16);
      ctx.beginPath(); ctx.moveTo(x, y + h); ctx.lineTo(x + w, y); ctx.stroke();
    }
  }

  // ---- 오버레이 ----
  if (spec.quad) { // 4분할 (도미니카공화국 등)
    for (const [qc, qx, qy] of spec.quad) {
      ctx.fillStyle = qc;
      ctx.fillRect(x + (qx * w) / 2, y + (qy * h) / 2, w / 2, h / 2);
    }
  }
  if (spec.can) { // 캔턴 (좌상단 사각)
    ctx.fillStyle = spec.can[0];
    ctx.fillRect(x, y, w * spec.can[1], h * spec.can[2]);
  }
  if (spec.bar) { // 깃대쪽 세로 바
    ctx.fillStyle = spec.bar[0];
    ctx.fillRect(x, y, w * spec.bar[1], h);
  }
  if (spec.tri) { // 깃대쪽 삼각형
    ctx.fillStyle = spec.tri;
    ctx.beginPath();
    ctx.moveTo(x, y); ctx.lineTo(x + w * 0.42, y + h / 2); ctx.lineTo(x, y + h);
    ctx.closePath(); ctx.fill();
  }
  if (spec.cross) { // 중앙 십자 (스위스/영국 근사/그리스 캔턴 등)
    const cw = Math.max(1.5, w * 0.14), ch = Math.max(1.5, h * 0.14);
    ctx.fillStyle = spec.cross[0];
    ctx.fillRect(x + w / 2 - cw / 2, y, cw, h);
    ctx.fillRect(x, y + h / 2 - ch / 2, w, ch);
    if (spec.cross[1]) {
      ctx.fillStyle = spec.cross[1];
      ctx.fillRect(x + w / 2 - cw / 4, y, cw / 2, h);
      ctx.fillRect(x, y + h / 2 - ch / 4, w, ch / 2);
    }
  }
  const drawDot = (d) => {
    ctx.fillStyle = d[0];
    ctx.beginPath();
    ctx.arc(x + w * d[1], y + h * d[2], Math.max(1.2, Math.min(w, h) * d[3]), 0, Math.PI * 2);
    ctx.fill();
  };
  if (spec.dot) drawDot(spec.dot);
  if (spec.dot2) drawDot(spec.dot2);
  if (spec.dots) for (const d of spec.dots) drawDot(d);
}
